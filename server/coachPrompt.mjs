/** 서행 기준 (도로교통법 제25조 제1항) — 이 아래면 게임이 알아서 맞춘 것이라 지표로 보내지 않는다 */
const SLOW_KMH = 20;

/**
 * **잘 달린 판의 기록에서 '게임이 해 준 것' 을 지운다.**
 *
 * 지표에서 뺐더니 이번에는 주행 기록에 적힌 "우측 방향지시등 켜짐" · "14km/h" 를 보고 칭찬했다 (작은 모델).
 * 기록은 판정 엔진이 남긴 문장이라 모양이 정해져 있으므로, 그 조각만 덜어 낸다 — 남는 것이 없으면 그 줄은
 * 통째로 뺀다. 어긴 판에서는 손대지 않는다: 거기서는 속도도 깜빡이도 이유가 될 수 있다.
 */
function withoutAutoFacts(text) {
  if (/방향지시등/.test(text)) return '';
  return text
    .replace(/\s*·?\s*\d+(?:\.\d+)?km\/h/g, '')
    .replace(/\s*—\s*·\s*/, ' — ')
    .replace(/\s+—\s*$/, '')
    .trim();
}

export function buildUserPrompt(run) {
  const lines = [];

  lines.push(`# 이번 주행`);
  lines.push(`Stage ${run.stage} · ${run.title}`);
  lines.push(`판정: ${run.grade} (${GRADE_BRIEF[run.grade] ?? ''})`);
  if (run.failReason) lines.push(`실패 사유: ${FAIL_BRIEF[run.failReason] ?? run.failReason}`);
  lines.push('');

  lines.push('# 판정 결과');
  if (run.violations.length === 0) {
    lines.push('위반 없음.');
  } else {
    for (const v of run.violations) {
      const b = VIOLATION_BRIEF[v.code];
      lines.push(
        `- ${b.title} (${b.law}) — ${v.place} · ${v.atTime.toFixed(1)}초` +
          (v.inSchoolZone ? ' · 어린이보호구역' : ''),
      );
    }
  }
  lines.push('');

  const s = run.stats;
  /*
    **잘 달린 판에서는 '안 함' 을 보내지 않는다.**

    서야 하는 자리는 판마다 다르다 — 정면신호가 녹색이고 보행자가 없으면 정지선 앞에서 서지 않는 것이 맞고,
    그래서 '정지선 앞 완전정지: 안 함' 이면서 위반이 없을 수 있다. 그런데 그 줄을 그대로 주면 모델이 **하지
    않아도 되는 일을 하지 않았다고 지적한다** — 실제로 녹색 · 보행자 없음 판에서 "반드시 멈춰야 합니다" 라는
    엉뚱한 코칭이 나왔다 (사용자가 짚었다).

    **판정이 위반이라고 하지 않은 것은 잘못이 아니다.** 그러니 무위반 판에는 **한 것만** 보낸다 — 칭찬거리는
    그것이고, 하지 않은 것은 애초에 요구되지 않았다. 어긴 판에는 둘 다 보낸다: 거기서는 '안 함' 이 이유다.
  */
  const clean = run.violations.length === 0 && !run.failReason;
  lines.push('# 세부 지표');
  if (!clean || s.cleanStopBeforeA) lines.push(`- 정지선 앞 완전정지: ${s.cleanStopBeforeA ? '함' : '안 함'}`);
  if (s.lateStopBeforeA) lines.push('- 정지선을 넘어서 정지함');
  if (!clean || s.stopBeforeC) lines.push(`- 우회전 후 횡단보도(C) 앞 정지: ${s.stopBeforeC ? '함' : '안 함'}`);
  /*
    **게임이 대신 해 주는 것은 잘 지켜졌을 때 아예 보내지 않는다.**

    속도는 교차로 · 횡단보도 부근에서 저절로 내려가고(game/Vehicle.ts), 방향지시등은 우회전 판이라 켜진 채로
    시작한다(game/Controls.ts). 그런데 이 값을 주면 모델이 "교차로 내 14km/h — 잘 지켰어요" 처럼 **학습자가
    하지 않은 일을 칭찬한다.** 지시로 막아 봤지만 작은 모델은 놓쳤다 — 아예 주지 않는 편이 확실하다.

    **어겼을 때는 보낸다.** 그때는 학습자가 한 일이고(깜빡이를 껐거나 서행 구간 밖에서 밟았거나), 짚어야 한다.
  */
  const speeding = s.maxSpeedInIntersection > SLOW_KMH;
  if (speeding) {
    lines.push(`- 교차로 내 최고속도: ${s.maxSpeedInIntersection.toFixed(0)}km/h (서행 기준 ${SLOW_KMH}km/h)`);
  }
  if (!s.signalAt30m) lines.push('- 30m 전 방향지시등: 꺼짐');
  lines.push(`- 소요 시간: ${s.elapsed.toFixed(1)}초`);
  lines.push('');

  /*
    **앞차는 사실만 넘긴다.** "앞차를 따라가서 위반했다" 는 해석은 모델이 판정 결과와
    겹쳐 보고 내릴 몫이다 — 앞차가 서지 않았다는 사실과 내 위반이 함께 있을 때만 그 말이 맞다.
  */
  if (run.lead) {
    const who =
      run.lead.behavior === 'rolling'
        ? run.lead.skippedStop
          ? '일시정지해야 할 자리에서 **서지 않고** 먼저 우회전해 나감'
          : '일시정지를 건너뛰는 성향이었지만 이번에는 서야 할 자리가 없었음'
        : '규정대로 정지하며 먼저 우회전함';
    lines.push('# 앞차');
    lines.push(`- 바로 앞에서 같은 길로 우회전한 차가 있었음: ${who}`);
    if (run.lead.minGap >= 0) {
      lines.push(`- 앞차와 가장 가까웠던 간격: ${run.lead.minGap.toFixed(1)}m`);
    }
    lines.push('');
  }

  if (run.log.length) {
    lines.push('# 주행 기록 (시간순 · 데이터)');
    for (const e of run.log) {
      const text = clean ? withoutAutoFacts(e.text) : e.text;
      if (text) lines.push(`${e.t.toFixed(1)}초 [${LEVEL_MARK[e.level] ?? e.level}] ${text}`);
    }
  }

  return lines.join('\n');
}
