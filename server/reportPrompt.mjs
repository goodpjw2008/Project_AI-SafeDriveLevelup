const pct = (r) => `${Math.round(r * 100)}%`;

/** 등급 이름 — src/rules/lawRules.ts 의 GRADE_TEXT 와 같은 말을 쓴다 */
const GRADE_TEXT = {
  PERFECT: 'PERFECT (완벽)',
  PASS: 'SUCCESS (위반 없음)',
  VIOLATION: 'VIOLATION (위반)',
  FAIL: 'FAIL (완주 실패)',
};

export function buildReportPrompt(s) {
  const lines = [];

  lines.push('# 전체');
  lines.push(`- 주행 ${s.runs}판 (서로 다른 Stage ${s.stagesPlayed}개)`);
  lines.push(`- 위반 없이 마친 판: ${s.cleanRuns}판 (${pct(s.cleanRuns / s.runs)})`);
  for (const [g, n] of Object.entries(s.grades)) {
    lines.push(`- ${GRADE_TEXT[g] ?? g}: ${n}판`);
  }
  lines.push('');

  lines.push('# 지점별 준수율 — 어디서 무너지는가');
  for (const p of s.points) {
    lines.push(`- ${p.label}: ${pct(p.rate)} (${p.kept}/${p.total}판)`);
  }
  lines.push('');

  if (s.byCode.length) {
    lines.push('# 반복된 위반 (많은 순)');
    for (const c of s.byCode) {
      const b = VIOLATION_BRIEF[c.code];
      lines.push(`- ${b ? `${b.title} (${b.law})` : c.code}: ${c.count}회`);
    }
    lines.push('');
  }

  if (s.trend) {
    lines.push('# 개선 추이 (무위반율)');
    lines.push(`- 초반 절반: ${pct(s.trend.early)}`);
    lines.push(`- 후반 절반: ${pct(s.trend.late)}`);
    lines.push('');
  } else {
    lines.push('# 개선 추이');
    lines.push('- 판이 적어 추이를 내지 않았습니다. 나아지고 있는지 여부를 말하지 마십시오.');
    lines.push('');
  }

  if (s.mostRetried) {
    lines.push(`# 가장 많이 다시 돈 판`);
    lines.push(`- Stage ${s.mostRetried.stage} — ${s.mostRetried.count}회`);
  }

  return lines.join('\n');
}
