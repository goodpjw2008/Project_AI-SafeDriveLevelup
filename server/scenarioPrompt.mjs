/**
 * 약점 요약 → 시나리오 생성 프롬프트.
 *
 * ## 이 프롬프트가 만드는 것은 **판단이 아니라 상황이다**
 *
 * 모델은 `ScenarioSpec` 의 값(신호를 어디서 시작할지, 보행자를 언제 어디로 내보낼지)만
 * 정한다. 무엇이 위반인지는 이 게임의 규칙 엔진(rules/lawRules.ts)이 100% 정확하게
 * 판정하고, 모델은 거기 손대지 않는다.
 *
 * 그래서 **모델이 틀려도 틀린 법을 가르치지 않는다.** 틀리면 "재미없는 판" 이 나올 뿐이고,
 * 그마저도 검증기(src/scenarios/validate.ts)가 걸러 낸다 — 규정대로 몰아 통과할 수
 * 있는지, 아무렇게나 몰면 걸리는지를 실제로 돌려 보고 나서 사람에게 준다.
 *
 * 프롬프트에서 얻으려는 것은 하나다: **이 학습자가 무너지는 지점을 다시 만나게 하는 것.**
 *
 * 순수 함수라 브라우저도 Node 도 Cloudflare Workers 도 그대로 쓴다.
 */

