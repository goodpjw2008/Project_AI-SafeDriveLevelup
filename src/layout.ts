/**
 * 교차로 좌표계 정의. 3D 씬과 법규 판정 엔진이 함께 참조하는 단일 기준이다.
 * (Three.js에 의존하지 않는 순수 상수 — 판정 엔진을 브라우저 없이 테스트할 수 있게 하기 위함)
 *
 * 좌표계:  +X = 동(East),  -X = 서(West),  +Z = 남(South),  -Z = 북(North)
 *
 * 플레이어는 남쪽에서 북쪽(-Z)으로 진입한다. **코스에 따라 둘 중 하나로 빠져나간다** —
 * 동쪽(+X)으로 **우회전**하거나(지금까지의 모든 판), 어린이보호구역 연습에서는 교차로를
 * **직진**으로 통과해 북쪽(-Z)으로 빠져나간다 (scenarios.ts 의 `drive`).
 *
 *                        북(-Z)
 *                          ↑
 *                  ▓▓▓▓ 횡단보도 B ▓▓▓▓          z ∈ [-18.8, -14.8]  ← 직진으로 빠져나가면 만난다
 *              ┌───────┬───────┐
 *              │       │       │
 *      서 ─────┤  교차로 박스   ├──────────────── 동 (+X)
 *              │|x|,|z| ≤ 9.8  │   코너   ▓▓▓▓   ← 우회전 후 진행 방향
 *              └───────┴───────┘  물림 5m ▓▓▓▓  횡단보도 C  x ∈ [14.8, 18.8]
 *                        코너 물림 5m
 *                  ▓▓▓▓ 횡단보도 A ▓▓▓▓          z ∈ [14.8, 18.8]
 *              ═══════════════════════           정지선 A   z = 20.8
 *                        ↑ 플레이어 진입
 *                       남(+Z)
 *
 *  두 횡단보도 사이(A 통과 → 코너 → C 도달)는 약 12m·서행 3~4초로,
 *  보행자를 확인하고 두 번째 정지를 판단할 시간이 확보된다.
 */

