/**
 * 이 게임의 이름과 한 줄 소개 — **여기 한 곳에서만 정한다.**
 *
 * 예전에는 같은 이름이 세 군데에 흩어져 있었다. 첫 화면의 큰 제목(Screens.ts),
 * 브라우저 탭 제목(index.html 의 `<title>`), 링크로 공유했을 때 보이는 설명
 * (`<meta name="description">`). 이름을 바꾸려면 세 곳을 다 찾아야 했고, 하나를
 * 빠뜨리면 탭 제목과 화면 제목이 서로 다른 이름을 말하게 된다.
 *
 * HTML 쪽은 `{{APP_NAME}}` 처럼 자리만 비워 두고 빌드할 때 이 값으로 채운다
 * (vite.config.ts). 화면을 그리고 나서 자바스크립트로 바꿔치기하지 않는 이유는,
 * 그러면 링크 미리보기를 만드는 쪽(자바스크립트를 돌리지 않는다)이 빈 제목을 읽기
 * 때문이다.
 */

/**
 * 이름 — **조각으로 적는다.**
 *
 * **`AI 어우참 안전운전 : 어린이보호구역 우회전 참교육`** — '어우참' 은 부제의 세 낱말
 * (**어**린이보호구역 · **우**회전 · **참**교육)의 첫 글자다. 무엇을 배우는가(어린이보호구역에서의 우회전)와
 * 어떻게 배우는가(틀린 습관을 AI 가 짚어 고치는 참교육)가 이름 셋에 다 들어 있다. 주행 중 로봇도 같은 이름
 * ('AI 어우참')을 쓰고, 학습자의 호칭도 이 이름을 따른다('어우참 L6' — curriculum.ts 의 courseTitle).
 *
 * 한때는 `Grand Turn Auto:우회전`, 그다음은 `AI 우린이 안전운전 : 우회전과 어린이보호구역 안전운전 시뮬레이션`
 * ('우린이' = **우**회전 + 어**린이**)이었다. 사용자가 지금 이름으로 바꾸며 "어우참 을 신호등의 색깔로" 라고 했다.
 *
 * **'우회전'은 어떤 경우에도 빠지지 않는다** — 이 게임이 다루는 것의 알맹이다.
 *
 * ## 왜 조각인가
 *
 * 글자마다 **서로 다른 색**을 준다 (아래 `tone`). 완성된 이름에서 글자를 찾아 자르지 않는 이유는, 같은 글자가
 * 뒤에도 또 나올 수 있어 찾아 자르면 이름을 바꿨을 때 엉뚱한 곳이 잘리기 때문이다. **조각을 먼저 정하고 이름을
 * 그 조각들로 만든다.**
 *
 * **길어지면 첫 화면의 히어로가 접힌다.** 이 값을 바꿀 때는 좁은 화면(390px)에서 어떻게 접히는지 보고 정한다 —
 * 히어로는 이름과 탭뿐인 자리라 이름이 흔들리면 그 화면에서 가장 큰 덩어리가 흔들린다.
 */

/**
 * 이름 한 조각.
 *
 * `tone` 이 붙은 조각만 색을 입는다 (index.html 의 `.brand-red` · `.brand-yellow` · `.brand-green`).
 * 색을 여기서 정하지 않고 이름만 주는 이유는, 값은 화면의 것이고 **여기서 정하는 것은
 * "이 글자가 신호등의 어느 등인가"** 이기 때문이다.
 */
export interface NamePart {
  text: string;
  /** 신호등의 세 등 — 적색 · 황색 · 녹색. `ai` 는 'AI' 배지 (신호등과 다른 모양 · 다른 색) */
  tone?: 'red' | 'yellow' | 'green' | 'ai';
}

/**
 * 이름의 조각들 — **'어우참' 세 글자가 신호등의 세 등이다.**
 *
 * 왼쪽부터 **적색 · 황색 · 녹색** — 우리나라 가로형 신호등이 켜지는 차례 그대로다. 셋 다 딱지(색깔 바탕)로
 * 그려, 나란히 서면 이름 자체가 신호등으로 보인다. 색이 가리키는 것도 맞아떨어진다.
 *  - **어**(어린이보호구역) — **적색.** 보호구역 노면이 실제로 붉고, 이 게임도 그렇게 그린다
 *    (game/Intersection.ts 의 drawSchoolZonePavement). 적색은 "먼저 선다" 이기도 하다.
 *  - **우**(우회전) — **황색.** 우회전은 멈출 수도 갈 수도 있는, **주의하며 판단하는** 자리다.
 *  - **참**(참교육) — **녹색.** 제대로 배워 가도 좋다는 뜻 — 레벨 뱃지 · 출발 버튼 · 경험치 막대가 쓰는 색이다.
 *
 * **`AI` 는 배지다** — AI 활용 공모전에 내는 작품이라 AI 가 돋보여야 한다(사용자가 "AI 가 너무 돋보이지 않아" 라고
 * 짚었다). 다만 신호등 딱지와 섞이면 넷째 등처럼 읽히므로 **모양도 색도 다르게** 둔다 — 둥근 알약 모양에, 신호에 없는
 * 파랑→보라 그라데이션과 은은한 빛, 흔히 AI 를 뜻하는 반짝이(✦). 색은 index.html 의 `.brand-ai` 가 정한다.
 *
 * `안전운전` 에는 색을 주지 않는다. 배지 하나와 세 등이 이미 주인공이라, 더 칠하면 무엇이 이름인지 흐려진다.
 */
export const APP_NAME_PARTS: readonly NamePart[] = [
  { text: 'AI', tone: 'ai' },
  { text: ' ' },
  { text: '어', tone: 'red' },
  { text: '우', tone: 'yellow' },
  { text: '참', tone: 'green' },
  { text: ' 안전운전' },
];

export const APP_NAME = APP_NAME_PARTS.map((p) => p.text).join('');

