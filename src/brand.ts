/**
 * 이 게임의 이름과 한 줄 소개 — **여기 한 곳에서만 정한다.**
 *
 * 예전에는 같은 이름이 세 군데에 흩어져 있었다. 첫 화면의 큰 제목(Screens.ts),
 * 브라우저 탭 제목(index.html 의 `<title>`), 링크로 공유했을 때 보이는 설명
 * (`<meta name="description">`). 이름을 바꾸려면 세 곳을 다 찾아야 했고, 하나를
 * 빠뜨리면 탭 제목과 화면 제목이 서로 다른 이름을 말하게 된다.
 *
 * HTML 쪽은 `{{APP_NAME}}` 처럼 자리만 비워 두고 빌드할 때 이 값으로 채운다
 * (vite.config.ts). 화면을 그리고 나서 자바스크립트로 바꿔치기하지 않는 이유는,
 * 그러면 링크 미리보기를 만드는 쪽(자바스크립트를 돌리지 않는다)이 빈 제목을 읽기
 * 때문이다.
 */

/**
 * 이름 — **조각으로 적는다.**
 *
 * **`AI 일시정지 안전운전 : 우회전과 어린이보호구역 운전 연습`** — 이 작품이 가르치는 것을 한 낱말로
 * 줄이면 **'일시정지'** 다. 판정 코드가 잡는 위반도, 경찰서에 물어볼 헷갈리는 상황도 모두 '여기서 서야
 * 하는가' 한 가지를 둘러싼 것이라, 그 낱말을 이름의 한가운데에 세운다. 뒤의 '안전운전' 은 **이것이 자동차를
 * 모는 이야기**라고 말한다 — 한때 '안전교육' 이었는데, 사용자가 "자동차 운전 느낌이 나지 않는다" 고 짚어 바꿨다.
 *
 * ## 왜 '우회전' 이 이름에서 빠졌는가
 *
 * 오래 '우회전' 을 이름에 두었다 — 이 게임이 다루는 것의 알맹이라서다. 그런데 **같은 낱말을 쓴 다른 작품이
 * 먼저 알려지면서**, 이름에 그 낱말을 두는 것만으로 따라 한 것처럼 보이게 됐다 (사용자가 짚었다).
 * 그래서 제목에서는 빼고 **부제에 남긴다** — 무엇을 다루는지는 부제가 말하고, 검색도 부제가 받는다.
 *
 * 학습자의 호칭도 이름을 따라 **'안전운전 Level6' · '안전운전 마스터'** 가 됐다 (curriculum.ts 의 courseTitle · 사용자 요청) —
 * 오래 '우회전 Level6' 이었는데, 부르는 말과 이름이 서로 다른 것을 가리키면 레벨이 무엇의 레벨인지부터 다시 알아봐야 한다.
 * 다만 호칭은 이름이 아니라 **키우는 능력의 이름**이라 **딱지로 칠하지 않는다** (ui/brandName.ts).
 *
 * ## 왜 조각인가
 *
 * 글자마다 **서로 다른 색**을 준다 (아래 `tone`). 완성된 이름에서 글자를 찾아 자르지 않는 이유는, 같은 글자가
 * 뒤에도 또 나올 수 있어 찾아 자르면 이름을 바꿨을 때 엉뚱한 곳이 잘리기 때문이다. **조각을 먼저 정하고 이름을
 * 그 조각들로 만든다.**
 *
 * **길어지면 첫 화면의 히어로가 접힌다.** 이 값을 바꿀 때는 좁은 화면(390px)에서 어떻게 접히는지 보고 정한다 —
 * 히어로는 이름과 탭뿐인 자리라 이름이 흔들리면 그 화면에서 가장 큰 덩어리가 흔들린다.
 */

/**
 * 이름 한 조각.
 *
 * `tone` 이 붙은 조각만 색을 입는다 (index.html 의 `.brand-red` · `.brand-yellow` · `.brand-green` · `.brand-zone`).
 * 색을 여기서 정하지 않고 이름만 주는 이유는, 값은 화면의 것이고 **여기서 정하는 것은
 * "이 글자가 신호등의 어느 등인가"** 이기 때문이다.
 */
export interface NamePart {
  text: string;
  /**
   * 신호등의 세 등 — 적색 · 황색 · 녹색. `yellow` 는 지금 부제의 '우회전' 딱지가 쓴다 (주의 표지처럼 노란 바탕 · 어두운 글자). `ai` 는 'AI' 배지 (신호등과 다른 모양 · 다른 색).
   * `zone` 은 어린이보호구역 — 보호구역 노면과 같은 붉은 바탕 (부제의 '어린이보호구역').
   * `stop` 은 **제목의 정지 표지** — 붉은 바탕의 '일시정지'.
   */
  tone?: 'red' | 'yellow' | 'green' | 'ai' | 'zone' | 'stop';
  /**
   * 줄이 접혀도 **한 덩어리로** 내려간다. 좁은 화면(390px)에서 부제가 두 줄이 될 때 마지막 낱말만 홀로 아랫줄에
   * 남았다 — 딱지의 여백만큼 윗줄이 길어져서다. '안전운전 학습' 을 묶어 두면 '… 어린이보호구역' 에서 끊긴다.
   */
  keep?: boolean;
}

/**
 * 이름의 조각들 — **'일시정지' 가 정지 표지다.**
 *
 * 붉은 딱지 하나. 실제 도로의 정지 표지가 그 색이라, 이름을 읽기 전에 **표지판 한 장이 선 것**으로 먼저
 * 보인다. 그 한 장이 이 작품이 가르치는 전부다 — 여기서 서는가.
 *
 * 예전 이름('AI 우회전 참교육')은 '우회전' 세 글자가 신호등의 세 등(적·황·녹)이었다. 지금은 부제가 딱지를
 * 맡는다 (아래 APP_TAGLINE_PARTS) — '우회전' 노랑 · '어린이보호구역' 보호구역색 · '일시정지' 정지 표지색.
 *
 * **`AI` 는 배지다** — AI 활용 공모전에 내는 작품이라 AI 가 돋보여야 한다(사용자가 "AI 가 너무 돋보이지 않아" 라고
 * 짚었다). 다만 표지 딱지와 섞이면 표지 하나가 더 선 것처럼 읽히므로 **모양도 색도 다르게** 둔다 — 둥근 알약 모양에,
 * 표지에 없는 파랑→보라 그라데이션과 은은한 빛, 흔히 AI 를 뜻하는 반짝이(✦). 색은 index.html 의 `.brand-ai` 가 정한다.
 *
 * `안전운전` 에는 색을 주지 않는다. 배지 하나와 표지 한 장이 이미 주인공이라, 더 칠하면 무엇이 이름인지 흐려진다.
 */
export const APP_NAME_PARTS: readonly NamePart[] = [
  { text: 'AI', tone: 'ai' },
  { text: ' ' },
  { text: '일시정지', tone: 'stop' },
  { text: ' 안전운전' },
];

export const APP_NAME = APP_NAME_PARTS.map((p) => p.text).join('');

