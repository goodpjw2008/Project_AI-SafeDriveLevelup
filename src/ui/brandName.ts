/**
 * **이름이 나오는 자리의 모양** — 어디서나 같은 얼굴이어야 한다.
 *
 * 첫 화면 제목의 이름을 딱지로 칠했더니(brand.ts · index.html 의 `.brand-green` · `.brand-ai`),
 * 사용자가 AI 분석 화면 · 추천 결과 · 주행 중 말풍선의 이름도 같은 모양으로 넣어 달라고 했다. 같은 이름이
 * 어떤 자리에서는 딱지이고 어떤 자리에서는 맨 글자면, 말하는 쪽과 작품 이름이 같은 것인지부터 다시 알아봐야 한다.
 *
 * ## 이름이 바뀌며 문장 속 이름은 'AI' 하나가 됐다
 *
 * 예전 이름('AI 우회전 참교육')은 '우회전' 세 글자를 떼어 **말하는 이의 이름**으로 쓸 수 있었다 —
 * "AI 우회전이 운전 습관을 분석하고 있습니다". 새 이름('AI 안전운전 레벨업')에는 떼어 쓸 조각이 없다 —
 * "AI 안전운전 레벨업이 분석하고 있습니다" 는 **장소가 사람 자리에 앉아** 읽히지 않는다. 그래서 문장에서는
 * **'AI' 하나**로 말하고, 배지만 붙인다 — 배지가 곧 이 작품의 얼굴이다.
 *
 * 색은 여기서 정하지 않는다 — 클래스만 붙이고 값은 index.html 이 정한다. HTML 에 바로 적힌 자리(분석 제목 ·
 * 추천 결과 문장 · 말풍선 이름 · 엔딩 이름)도 같은 마크업을 쓴다.
 */

import { APP_NAME_PARTS } from '../brand';

/**
 * **'AI' 배지** — 둥근 알약 모양 · 파랑→보라 그라데이션 · 반짝이(✦). AI 활용 공모전 작품이라 이름의 'AI' 가 돋보여야
 * 한다(사용자가 짚었다). 이름 딱지와 모양 · 색을 달리해 딱지 하나가 더 선 것처럼 읽히지 않게 한다 (index.html 의 `.brand-ai`).
 */
export const AI_BADGE_HTML = '<span class="brand-ai">AI</span>';

/**
 * **이름 한 줄** (`AI 안전운전 레벨업`) — brand.ts 의 조각에서 만든다.
 *
 * 첫 화면의 제목은 Screens.ts 가 같은 조각으로 직접 그린다. 이것은 제목 밖에서 이름을 **통째로** 적는 자리
 * (About 창의 한 줄)가 쓴다 — 두 벌로 적어 두면 이름을 바꿀 때 한쪽만 고쳐진다.
 */
export const BRAND_NAME_HTML = APP_NAME_PARTS.map((p) =>
  p.tone ? `<span class="brand-${p.tone}">${p.text}</span>` : p.text,
).join('');

/**
 * **홀로 선 'AI' 를 배지로 칠한다** — 말하는 이의 이름('AI 가 분석하고 있습니다')이든, 판 이름
 * (`AI 추천 시나리오 2484` · `AI 시범`)이든 같다.
 *
 * 사용자가 짚었다 — "주행 결과를 보여 줄 때 'AI 추천 시나리오 2484' 이렇게 나오는데, 여기의 AI 부분도
 * 타이틀의 예쁜 AI 를 가져다 써 줘." AI 활용 공모전 작품이라 AI 라는 글자는 어디에 있든 같은 얼굴이어야 한다.
 *
 * **이스케이프한 뒤에 부른다** — 배지 마크업이 다시 이스케이프되면 태그가 글자로 보인다.
 */
export function withAiBadge(escapedHtml: string): string {
  return escapedHtml.replace(/\bAI\b/g, AI_BADGE_HTML);
}
